"""fastMD input and output (fastMD main b35e30a, https://github.com/Chenghao-Wu/fastMD).

Formats, from the fastMD source (src/io/config.cpp, table_parser.cpp, lammps_data.cpp):
  * config: one keyword per line, 0-based type indices; `table ti tj file keyword force` is symmetric
    and every type pair needs one; `bond_table t file keyword force`; `angle_table t file keyword
    degrees` (theta in degrees, force per degree).
  * table files: a line starting with the keyword, then `N n`, then n rows `i x E F` on a uniform
    grid, F = -dE/dx; kernels interpolate linearly and clamp x to [x_first, x_last].
  * LAMMPS data file, atom style molecular (`id mol type x y z ix iy iz`), per-type masses,
    Velocities, Bonds, Angles. Velocities are not generated by fastMD.
  * exclusions: without dihedrals or Ewald fastMD excludes only bonded (1-2) pairs from the pair
    potential. 1-3 exclusions are therefore written as extra bonds of a zero-energy bond type
    (`EXCLUSION_BOND_KEYWORD`), which excludes them through the same mechanism.
  * thermo: `thermo 1 <freq> <file>` (the README's <on> is an integer flag); columns
    `step KE PE T Pxx Pyy Pzz Pxy Pxz Pyz`, energies per atom.
  * trajectories: fastMD format v2 (`traj file linear N`), read with fastmd.trajectory.
Units: nm, ps, amu, kJ/mol; temperatures are k_B T (kJ/mol), pressures kJ/mol/nm^3.
"""
from __future__ import annotations

import os
import subprocess
from pathlib import Path

import numpy as np

KB_KJ_PER_MOL_K = 0.00831446261815324
ATM_KJ_MOL_NM3 = 101325.0 * 1e-27 * 6.02214076e23 / 1000.0     # 1 atm in kJ/mol/nm^3 (0.0610193)
BAR_PER_KJ_MOL_NM3 = 16.6053906660
EXCLUSION_BOND_KEYWORD = 'EXCL13'


def kT(temperature_K):
    """k_B T in kJ/mol, fastMD's temperature unit."""
    return KB_KJ_PER_MOL_K * float(temperature_K)


def write_table(path, keyword, x, energy, force, *, header=''):
    """Append one table (uniform grid x, energy E, force F = -dE/dx) to a fastMD/LAMMPS table file."""
    x, energy, force = (np.asarray(v, float) for v in (x, energy, force))
    if not (x.ndim == energy.ndim == force.ndim == 1 and len(x) == len(energy) == len(force) >= 2):
        raise ValueError('table columns must be 1-d arrays of equal length >= 2')
    dx = np.diff(x)
    if not np.all(dx > 0) or np.max(np.abs(dx - dx.mean())) > 1e-6 * dx.mean():
        raise ValueError('table grid must be uniform and increasing')
    if not np.all(np.isfinite(energy)) or not np.all(np.isfinite(force)):
        raise ValueError(f'non-finite values in table {keyword}')
    lines = [f'# {header}'] if header else []
    lines += ['', keyword, f'N {len(x)}', '']
    lines += [f'{i + 1} {xi:.10g} {ei:.10g} {fi:.10g}' for i, (xi, ei, fi) in enumerate(zip(x, energy, force))]
    with open(path, 'a') as f:
        f.write('\n'.join(lines) + '\n')


def wrap(pos, box):
    """Positions wrapped into [0, L) and the image counts."""
    pos = np.asarray(pos, float)
    box = np.asarray(box, float)
    img = np.floor(pos / box).astype(int)
    return pos - img * box, img


def maxwell_velocities(masses, temperature_K, seed):
    """Maxwell-Boltzmann velocities (nm/ps) without centre-of-mass drift."""
    rng = np.random.default_rng(seed)
    m = np.asarray(masses, float)
    v = rng.normal(size=(len(m), 3)) * np.sqrt(kT(temperature_K) / m)[:, None]
    v -= (m[:, None] * v).sum(0) / m.sum()
    return v


def write_data(path, *, pos, box, types, type_masses, mol, bonds=(), bond_types=(), n_bond_types=0,
               angles=(), angle_types=(), n_angle_types=0, dihedrals=(), dihedral_types=(), n_dihedral_types=0,
               velocities=None, title='ascg CG system'):
    """LAMMPS data file (atom style molecular) for fastMD. types / bond_types / angle_types are 0-based;
    pos are unwrapped (wrapped here, with image flags); box is orthorhombic (Lx, Ly, Lz) from the origin."""
    box = np.asarray(box, float).reshape(3)
    xw, img = wrap(pos, box)
    types = np.asarray(types, int)
    mol = np.asarray(mol, int)
    bonds = np.asarray(bonds, int).reshape(-1, 2)
    angles = np.asarray(angles, int).reshape(-1, 3)
    dihedrals = np.asarray(dihedrals, int).reshape(-1, 4)
    n, nt = len(types), len(type_masses)
    if types.min() < 0 or types.max() >= nt:
        raise ValueError('atom types out of range')
    out = [title, '', f'{n} atoms', f'{nt} atom types']
    if len(bonds):
        out += [f'{len(bonds)} bonds', f'{n_bond_types} bond types']
    if len(angles):
        out += [f'{len(angles)} angles', f'{n_angle_types} angle types']
    if len(dihedrals):
        out += [f'{len(dihedrals)} dihedrals', f'{n_dihedral_types} dihedral types']
    out += ['', f'0.0 {box[0]:.10g} xlo xhi', f'0.0 {box[1]:.10g} ylo yhi', f'0.0 {box[2]:.10g} zlo zhi',
            '', 'Masses', '']
    out += [f'{t + 1} {float(m):.10g}' for t, m in enumerate(type_masses)]
    out += ['', 'Atoms # molecular', '']
    out += [f'{i + 1} {mol[i] + 1} {types[i] + 1} {xw[i, 0]:.8f} {xw[i, 1]:.8f} {xw[i, 2]:.8f} '
            f'{img[i, 0]} {img[i, 1]} {img[i, 2]}' for i in range(n)]
    if velocities is not None:
        v = np.asarray(velocities, float)
        out += ['', 'Velocities', '']
        out += [f'{i + 1} {v[i, 0]:.8f} {v[i, 1]:.8f} {v[i, 2]:.8f}' for i in range(n)]
    if len(bonds):
        out += ['', 'Bonds', '']
        out += [f'{k + 1} {int(t) + 1} {a + 1} {b + 1}' for k, ((a, b), t) in enumerate(zip(bonds, bond_types))]
    if len(angles):
        out += ['', 'Angles', '']
        out += [f'{k + 1} {int(t) + 1} {a + 1} {b + 1} {c + 1}'
                for k, ((a, b, c), t) in enumerate(zip(angles, angle_types))]
    if len(dihedrals):
        out += ['', 'Dihedrals', '']
        out += [f'{k + 1} {int(t) + 1} {a + 1} {b + 1} {c + 1} {d + 1}'
                for k, ((a, b, c, d), t) in enumerate(zip(dihedrals, dihedral_types))]
    Path(path).write_text('\n'.join(out) + '\n')


def conf_text(*, data_file, ntypes, rc, skin, dt, nsteps, ensemble, pair_tables, bond_tables=(), angle_tables=(),
              dihedral_tables=(), thermo=None, traj=None, restart=None, extra=()):
    """fastMD config. pair_tables: [(ti, tj, file, keyword)], bond_tables / angle_tables: [(t, file, keyword)],
    dihedral_tables: [(t, file, keyword[, 'cbt'])];
    ensemble: e.g. ('nvt_nh', kT, kT, tdamp) or ('npt_nh', kT, kT, tdamp, P, P, pdamp);
    thermo (freq, file), traj (file, every), restart (freq, file)."""
    lines = [f'ntypes {ntypes}', f'rc {rc:.10g}', f'skin {skin:.10g}', f'dt {dt:.10g}', f'nsteps {int(nsteps)}',
             ' '.join(str(e) if isinstance(e, str) else f'{e:.10g}' for e in ensemble)]
    lines += [f'table {ti} {tj} {f} {k} force' for ti, tj, f, k in pair_tables]
    lines += [f'bond_table {t} {f} {k} force' for t, f, k in bond_tables]
    lines += [f'angle_table {t} {f} {k} degrees' for t, f, k in angle_tables]
    # dihedral_table (fastMD PR #3): phi in degrees on [-180, 180], force per degree;
    # entries (t, file, keyword[, option]), option 'cbt' = combined bending-torsion
    lines += [' '.join(['dihedral_table', str(e[0]), e[1], e[2], 'degrees', *e[3:]]) for e in dihedral_tables]
    if thermo:
        lines.append(f'thermo 1 {int(thermo[0])} {thermo[1]}')       # <on> is the integer flag 1
    if traj:
        lines.append(f'traj {traj[0]} linear {int(traj[1])}')
    if restart:
        lines.append(f'restart {int(restart[0])} {restart[1]}')
    lines += list(extra)
    lines.append(f'lammps_data_file {data_file}')
    return '\n'.join(lines) + '\n'


def read_thermo(path):
    """thermo.dat as a dict of arrays: step, ke, pe (per atom), T (k_B T), P (scalar, kJ/mol/nm^3), Pxx..Pyz."""
    a = np.loadtxt(path, comments='#', ndmin=2)
    names = ['step', 'ke', 'pe', 'T', 'Pxx', 'Pyy', 'Pzz', 'Pxy', 'Pxz', 'Pyz']
    out = {k: a[:, i] for i, k in enumerate(names[:a.shape[1]])}
    out['P'] = (out['Pxx'] + out['Pyy'] + out['Pzz']) / 3.0
    return out


def read_restart(path):
    """fastMD restart (LAMMPS data, `Atoms # full` with image flags, Velocities) -> (unwrapped positions, box
    lengths, velocities), atoms in id order; the box is taken from its lower corner."""
    lines = Path(path).read_text().splitlines()
    lo, hi = np.zeros(3), np.zeros(3)
    for l in lines[:40]:
        w = l.split()
        for k, ax in enumerate('xyz'):
            if len(w) >= 4 and w[2] == f'{ax}lo' and w[3] == f'{ax}hi':
                lo[k], hi[k] = float(w[0]), float(w[1])
    box = hi - lo

    def section(name):
        i = next(k for k, l in enumerate(lines) if l.split()[:1] == [name])
        rows = []
        for l in lines[i + 1:]:
            w = l.split('#')[0].split()
            if not w:
                if rows:
                    break
                continue
            if not w[0].lstrip('-').isdigit():
                break
            rows.append([float(v) for v in w])
        return np.array(rows)
    at = section('Atoms')
    at = at[np.argsort(at[:, 0])]
    x = at[:, 4:7] - lo + at[:, 7:10] * box          # full style: id mol type q x y z ix iy iz
    v = section('Velocities')
    v = v[np.argsort(v[:, 0])][:, 1:4]
    return x, box, v


def read_trajectory(path):
    """fastMD v2 trajectory via the engine's own reader (fastmd.trajectory, numpy only)."""
    from fastmd.trajectory import Trajectory
    return Trajectory(path)


def fastmd_binary():
    b = os.environ.get('FASTMD_BINARY')
    if not b or not Path(b).is_file():
        raise RuntimeError('set FASTMD_BINARY to the fastMD executable (e.g. ~/software/fastMD/build/fastmd)')
    return b


def run(conf, workdir, *, log='fastmd.log', binary=None, env=None, timeout=None):
    """Run the fastMD command-line program on `conf` inside `workdir`; raises with the log tail on failure."""
    workdir = Path(workdir)
    with open(workdir/log, 'w') as f:
        p = subprocess.run([binary or fastmd_binary(), str(conf)], cwd=workdir, stdout=f, stderr=subprocess.STDOUT,
                           env={**os.environ, **(env or {})}, timeout=timeout)
    if p.returncode != 0:
        tail = (workdir/log).read_text().splitlines()[-15:]
        raise RuntimeError(f'fastMD failed ({p.returncode}) in {workdir}:\n' + '\n'.join(tail))
    return workdir/log
